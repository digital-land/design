#!/usr/bin/env python3
"""Create content/abbreviation from "Long name (ABBR)" patterns that expand to a known term.

`terms` is a semi-colon separated list of the terms an abbreviation can stand for, so a
reader can tell when the abbreviation needs disambiguating.
"""

import re
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

CONTENT = Path("content")
SMALL = {"of", "and", "the", "for", "to", "in", "on", "a", "an", "or"}
PATTERN = re.compile(
    r"((?:[A-Z][A-Za-z’'-]*|of|and|the|for|to|in|on)(?: (?:[A-Za-z][A-Za-z’'-]*|of|and|the|for|to|in|on)){1,7}) "
    r"\(\*{0,2}([A-Z][A-Za-z]{1,7})\*{0,2}\)"
)


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def matches(words, abbr):
    """True if the abbreviation's letters are the initials of the trailing words."""
    initials = [w[0].upper() for w in words if w.lower() not in SMALL]
    return "".join(initials[-len(abbr):]) == abbr.upper() or "".join(initials) == abbr.upper()


def expansions(text, terms):
    for m in PATTERN.finditer(text):
        words = m.group(1).split()
        abbr = m.group(2)
        if not abbr.isupper() and not re.fullmatch(r"[A-Z][A-Za-z]+", abbr):
            continue
        for start in range(len(words)):  # try shorter tails: "the Community Infrastructure Levy"
            tail = words[start:]
            if not tail or tail[0].lower() in SMALL:
                continue
            if matches(tail, abbr):
                t = slug(" ".join(tail))
                for cand in (t, t.rstrip("s")):
                    if cand in terms:
                        yield abbr, cand
                        break
                else:
                    continue
                break


NOISE = ("budget-2026", "lasting-power", "change-the-register", "public-health", "council-tax", "register-your-rental")


def gaps(terms):
    """Abbreviations in planning snapshots whose expansion is not yet a term."""
    count = defaultdict(set)
    for p in (CONTENT / "snapshot").glob("*.md"):
        if any(n in p.name for n in NOISE):
            continue
        for m in PATTERN.finditer(p.read_text(encoding="utf-8")):
            words = m.group(1).split()
            abbr = m.group(2)
            for start in range(len(words)):
                tail = words[start:]
                if tail[0].lower() not in SMALL and matches(tail, abbr) and len(abbr) > 1:
                    t = slug(" ".join(tail))
                    if t not in terms and t.rstrip("s") not in terms:
                        count[(abbr.upper(), t)].add(p.name)
                    break
    rows = sorted(count.items(), key=lambda kv: -len(kv[1]))
    lines = [
        "# Abbreviations without a term",
        "",
        "Generated by `bin/abbreviations.py`. These expansions appear as `Long name (ABBR)` in the snapshots",
        "but there is no term yet. Add the term, then rerun the script to create the abbreviation.",
        "",
        "| Abbreviation | Expansion | Pages |",
        "| --- | --- | --- |",
    ]
    lines += [f"| {a} | {t.replace('-', ' ')} | {len(f)} |" for (a, t), f in rows if len(f) >= 2]
    Path("notes/abbreviation-gaps.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    terms = {p.stem for p in (CONTENT / "term").glob("*.md")}
    found = defaultdict(set)
    sources = list((CONTENT / "snapshot").glob("*.md")) + list((CONTENT / "quotation").rglob("*.md"))
    sources += list((CONTENT / "term").glob("*.md"))
    for p in sources:
        for abbr, term in expansions(p.read_text(encoding="utf-8"), terms):
            found[abbr.upper()].add(term)
    gaps(terms)
    out = CONTENT / "abbreviation"
    out.mkdir(exist_ok=True)
    today = date.today().isoformat()
    for abbr, ts in sorted(found.items()):
        path = out / f"{abbr.lower()}.md"
        if path.exists():
            continue
        path.write_text(
            "\n".join(
                [
                    "---",
                    "prefix: abbreviation",
                    f"reference: {abbr}",
                    f"name: {abbr}",
                    f"terms: {'; '.join(sorted(ts))}",
                    f"entry-date: {today}",
                    "---",
                    "",
                ]
            ),
            encoding="utf-8",
        )
    print(f"{len(found)} abbreviations", file=sys.stderr)


if __name__ == "__main__":
    main()
