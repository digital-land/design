#!/usr/bin/env python3
"""Find sentences in the GOV.UK snapshots that look like definitions of terms.

Writes candidate quotations (role: candidate) to content/quotation and a review list to
notes/govuk-candidates.md. A reviewer changes `role: candidate` to `definition` (or `use`);
bin/build-terms.py only uses definitions.
"""

import re
import sys
from datetime import date
from pathlib import Path

import yaml

CONTENT = Path("content")
GLOSSARY = "annex-b-glossary"
STRONG = r"(?:means|is defined as|are defined as|refers to|is described as|are described as)"
WEAK = r"(?:is the|are the|is a|is an|are a|is any|is when|is where|is an)"
MAX_PER_TERM = 5


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def read(path):
    m = re.match(r"---\n(.*?)\n---\n?(.*)", path.read_text(encoding="utf-8"), re.S)
    return (yaml.safe_load(m.group(1)) or {}, m.group(2)) if m else ({}, "")


def pattern(names):
    alt = "|".join(re.escape(n) for n in sorted(names, key=len, reverse=True))
    start = r"(?:^|[.!?:]\s+)(?:[-*]\s+)?"
    tail = r"s?[*\"”’'_]*\s*(?:\([^)]*\)\s*)?"
    return re.compile(
        start + r"[*\"“‘'_]*(?:(?:the |a |an )?(?:" + alt + r")" + tail + STRONG
        + r"|(?:" + alt + r")" + tail + WEAK + r")\b",
        re.I,
    )


def main():
    terms = {}
    for f in sorted((CONTENT / "term").glob("*.md")):
        fm, _ = read(f)
        names = {fm.get("name"), f.stem.replace("-", " ")}
        terms[f.stem] = pattern({n for n in names if n and len(n) > 3})
    today = date.today().isoformat()
    found = {}
    for f in sorted((CONTENT / "snapshot").glob("*.md")):
        if GLOSSARY in f.name:
            continue
        fm, body = read(f)
        url = fm.get("document-url") or ""
        heading, anchor = "", ""
        for line in body.splitlines():
            if line.startswith("#"):
                heading = line.lstrip("# ").strip()
                anchor = slug(heading)
                continue
            if not line.strip() or len(line) > 1500:
                continue
            low = line.lower()
            for term, pat in terms.items():
                if term.replace("-", " ") not in low and not re.search(re.escape(term[:6]), low):
                    continue
                m = pat.search(line)
                if not m:
                    continue
                text = re.sub(r"^[-*]\s+", "", line[m.start():].lstrip(".!? ")).strip()
                found.setdefault(term, []).append(
                    {
                        "page": fm.get("name", f.stem),
                        "reference": fm.get("reference", f.stem),
                        "url": url + (f"#{anchor}" if anchor else ""),
                        "text": text,
                    }
                )
    others = {}
    generic = re.compile(
        r"^(?:[-*]\s+)?[*\"“‘]([A-Za-z][A-Za-z' -]{3,50}?)[*\"”’]\s+(?:means|is defined as|are defined as)\b(.{0,200})"
    )
    for f in sorted((CONTENT / "snapshot").glob("*.md")):
        if GLOSSARY in f.name:
            continue
        fm, body = read(f)
        for line in body.splitlines():
            m = generic.match(line.strip())
            if m and slug(m.group(1)) not in terms:
                others.setdefault(slug(m.group(1)), (m.group(1), fm.get("name", f.stem), line.strip()))
    report = ["# GOV.UK candidate definitions", "",
        "Generated by `bin/govuk-candidates.py`. Review each quotation in `content/quotation`:",
        "change `role: candidate` to `definition` if it defines the term, or to `use` if it does not.", ""]
    written = 0
    for term in sorted(found):
        recs = found[term][:MAX_PER_TERM]
        report += [f"## [{term}](../content/term/{term}.md)", ""]
        for i, r in enumerate(recs, 1):
            ref = f"govuk-{slug(r['reference'].replace('/', '-'))}-{term}"[:150]
            ref = f"{ref}-{i}" if i > 1 else ref
            lines = [
                "---",
                f"reference: {ref}",
                f"name: {yaml.safe_dump(r['page'], width=1000).strip().removesuffix('...').strip()}",
                f"url: {r['url']}",
                "source-class: GOV.UK",
                "role: candidate",
                f"terms:\n- {term}",
                f"entry-date: {today}",
                "---",
                "",
                r["text"],
                "",
            ]
            (CONTENT / "quotation" / f"{ref}.md").write_text("\n".join(lines), encoding="utf-8")
            written += 1
            report.append(f"- {r['page']}: {r['text'][:200]}")
        report.append("")
    report += [f"## Other defined terms not yet in the glossary ({len(others)})", ""]
    report += [f"- **{n}** ({page}): {text[:220]}" for n, page, text in others.values()]
    Path("notes/govuk-candidates.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    print(f"{written} candidates for {len(found)} terms", file=sys.stderr)


if __name__ == "__main__":
    main()
